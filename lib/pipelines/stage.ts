import { createHash } from 'node:crypto'
import { eq, inArray, lt } from 'drizzle-orm'
import { db, pool } from '@/lib/db'
import { pipelineStageTables } from '@/lib/db/schema'
import { NonRetryableError } from './io'
import type { Row } from './transforms'

/**
 * Run staging (several sources): the rows of a Join's right
 * side, read in full before the driver streams. One table per (run, Join) in
 * the nexus_stage schema: the row as JSON, its normalized join key `_k`
 * (indexed), and the pass (`_stage_part` = source step) and chunk that wrote
 * it, so a resumed chunk replaces its earlier copy. Registered in
 * pipeline_stage_tables; dropped when the run finishes, or by the cron sweep.
 */

const SCHEMA = 'nexus_stage'
const KEYS_PER_QUERY = 5000
/** Staging older than this belongs to a run that never finished. */
export const STAGE_MAX_AGE_HOURS = 48

const qIdent = (name: string) => `"${name.replace(/"/g, '""')}"`
const rel = (table: string) => `${qIdent(SCHEMA)}.${qIdent(table)}`
const short = (s: string, n: number) => createHash('sha1').update(s).digest('hex').slice(0, n)

export function stageTableName(runId: string, nodeId: string) {
  return `stg_${short(runId, 16)}_${short(nodeId, 8)}`
}

const jsonSafe = (row: Row) => JSON.stringify(row, (_k, v) => (typeof v === 'bigint' ? v.toString() : v))

/** Creates (once) the staging table of a run's Join and registers it for cleanup. */
export async function createStageTable(opts: { workspaceId: string; runId: string; nodeId: string }): Promise<string> {
  const table = stageTableName(opts.runId, opts.nodeId)
  await db.insert(pipelineStageTables).values({ tableName: table, workspaceId: opts.workspaceId, runId: opts.runId, nodeId: opts.nodeId }).onConflictDoNothing()
  await pool.query(`CREATE SCHEMA IF NOT EXISTS ${qIdent(SCHEMA)}`)
  await pool.query(
    `CREATE TABLE IF NOT EXISTS ${rel(table)} (
       "_stage_row" bigint GENERATED BY DEFAULT AS IDENTITY,
       "_stage_part" text NOT NULL,
       "_stage_chunk" integer NOT NULL,
       "_k" text,
       "row" jsonb NOT NULL)`
  )
  await pool.query(`CREATE INDEX IF NOT EXISTS ${qIdent(`${table}_k`)} ON ${rel(table)} ("_k")`)
  await pool.query(`CREATE INDEX IF NOT EXISTS ${qIdent(`${table}_pc`)} ON ${rel(table)} ("_stage_part", "_stage_chunk")`)
  return table
}

/** Writes one staged chunk; a chunk written before (a resumed or retried chunk) is replaced in the same transaction. */
export async function writeStageChunk(table: string, part: string, chunk: number, rows: { key: string | null; row: Row }[]) {
  const client = await pool.connect()
  try {
    await client.query('BEGIN')
    await client.query(`DELETE FROM ${rel(table)} WHERE "_stage_part" = $1 AND "_stage_chunk" = $2`, [part, chunk])
    for (let i = 0; i < rows.length; i += 1000) {
      const params: unknown[] = [part, chunk]
      const values = rows.slice(i, i + 1000).map((r) => {
        params.push(r.key, jsonSafe(r.row))
        return `($1, $2, $${params.length - 1}, $${params.length}::jsonb)`
      })
      await client.query(`INSERT INTO ${rel(table)} ("_stage_part", "_stage_chunk", "_k", "row") VALUES ${values.join(', ')}`, params)
    }
    await client.query('COMMIT')
  } catch (err) {
    await client.query('ROLLBACK').catch(() => undefined)
    throw err
  } finally {
    client.release()
  }
}

/** Staged rows of these normalized keys, grouped by key, in staging order. */
export async function lookupStage(table: string, keys: string[]): Promise<Map<string, Row[]>> {
  const out = new Map<string, Row[]>()
  if (!keys.length) return out
  const { rows: exists } = await pool.query<{ r: string | null }>('SELECT to_regclass($1)::text AS r', [rel(table)])
  if (!exists[0]?.r) throw new NonRetryableError('The right side of a Join was not staged for this run. Run the pipeline again.')
  for (let i = 0; i < keys.length; i += KEYS_PER_QUERY) {
    const { rows } = await pool.query<{ k: string; row: Row }>(`SELECT "_k" AS k, "row" FROM ${rel(table)} WHERE "_k" = ANY($1::text[]) ORDER BY "_stage_row"`, [keys.slice(i, i + KEYS_PER_QUERY)])
    for (const r of rows) out.set(r.k, [...(out.get(r.k) ?? []), r.row])
  }
  return out
}

/** Disk used by a run's staging tables (bytes), for the run log. */
export async function stageSize(runId: string): Promise<number> {
  const tables = await db.select({ tableName: pipelineStageTables.tableName }).from(pipelineStageTables).where(eq(pipelineStageTables.runId, runId))
  let bytes = 0
  for (const t of tables) {
    const { rows } = await pool.query<{ n: string | null }>('SELECT pg_total_relation_size(to_regclass($1))::text AS n', [rel(t.tableName)])
    bytes += Number(rows[0]?.n ?? 0)
  }
  return bytes
}

async function drop(tables: string[]) {
  for (const t of tables) await pool.query(`DROP TABLE IF EXISTS ${rel(t)}`)
  if (tables.length) await db.delete(pipelineStageTables).where(inArray(pipelineStageTables.tableName, tables))
}

/** Drops a run's staging (when the run finishes). */
export async function dropStageTables(runId: string) {
  const tables = await db.select({ tableName: pipelineStageTables.tableName }).from(pipelineStageTables).where(eq(pipelineStageTables.runId, runId))
  await drop(tables.map((t) => t.tableName))
}

/** Cron tick: drops staging left behind by runs that never finished. Never throws. */
export async function sweepStageTables(maxAgeHours = STAGE_MAX_AGE_HOURS): Promise<number> {
  try {
    const old = await db
      .select({ tableName: pipelineStageTables.tableName })
      .from(pipelineStageTables)
      .where(lt(pipelineStageTables.createdAt, new Date(Date.now() - maxAgeHours * 3_600_000)))
      .limit(200)
    await drop(old.map((t) => t.tableName))
    return old.length
  } catch (err) {
    console.error('[stage] sweep failed:', err instanceof Error ? err.message : err)
    return 0
  }
}
